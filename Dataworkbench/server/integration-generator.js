'use strict';

const crypto = require('node:crypto');

const PROVIDERS = Object.freeze({
  slack: {
    label: 'Slack incoming webhook',
    requiredEnvironment: ['DLP_SLACK_WEBHOOK_URL'],
    description: 'Posts minimized DLP incident summaries to a Slack incoming webhook.',
  },
  servicenow: {
    label: 'ServiceNow incident API',
    requiredEnvironment: ['DLP_SERVICENOW_INSTANCE', 'DLP_SERVICENOW_TOKEN'],
    optionalEnvironment: ['DLP_SERVICENOW_TABLE'],
    description: 'Creates incidents through the ServiceNow Table API using a bearer token.',
  },
  webhook: {
    label: 'Generic REST webhook',
    requiredEnvironment: ['DLP_WEBHOOK_URL'],
    optionalEnvironment: ['DLP_WEBHOOK_TOKEN'],
    description: 'Posts a minimized JSON incident summary to an HTTPS webhook.',
  },
});

function badRequest(message) {
  throw Object.assign(new Error(message), { statusCode: 400 });
}

function normalizeSpec(input = {}) {
  const provider = String(input.provider || '').trim().toLowerCase();
  if (!Object.hasOwn(PROVIDERS, provider)) badRequest('Select Slack, ServiceNow, or Generic REST webhook.');
  const name = String(input.name || PROVIDERS[provider].label).trim();
  if (!name || name.length > 80 || !/^[a-zA-Z0-9 ._-]+$/.test(name)) badRequest('Integration name may contain letters, numbers, spaces, dots, underscores, and hyphens only.');
  const studioUrl = String(input.studioUrl || 'http://127.0.0.1:3100').trim().replace(/\/$/, '');
  let parsed;
  try { parsed = new URL(studioUrl); } catch { badRequest('Response Studio URL is invalid.'); }
  if (parsed.protocol !== 'http:' || !['127.0.0.1', 'localhost', '::1'].includes(parsed.hostname)) badRequest('Generated sync scripts may query Response Studio only through a loopback HTTP URL.');
  if (parsed.pathname !== '/' || parsed.search || parsed.hash || parsed.username || parsed.password) badRequest('Response Studio URL must contain only scheme, loopback host, and port.');
  const lookbackHours = Math.min(2160, Math.max(1, Math.trunc(Number(input.lookbackHours) || 24)));
  const fileStem = name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60) || `${provider}-dlp-sync`;
  return { provider, name, studioUrl, lookbackHours, fileName: `Sync-DlpTo-${fileStem}.ps1` };
}

function powerShell(spec) {
  const integrationName = spec.name.replace(/'/g, '');
  return `<#
.SYNOPSIS
Exports minimized, redacted DLP incident summaries from DLP Response Studio to ${PROVIDERS[spec.provider].label}.
.DESCRIPTION
Generated by DLP Response Studio. This script never requests detected values, document content, user addresses, or sender addresses.
Secrets are read from environment variables and are never persisted in the state file. Use -DryRun before enabling delivery.
#>
[CmdletBinding()]
param(
    [uri]$StudioUrl = '${spec.studioUrl}',
    [string]$StatePath = (Join-Path $PSScriptRoot '.dlp-${spec.provider}-sync-state.json'),
    [ValidateRange(1, 2160)][int]$InitialLookbackHours = ${spec.lookbackHours},
    [switch]$DryRun
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$IntegrationType = '${spec.provider}'
$IntegrationName = '${integrationName}'

function Get-SafeValue {
    param([AllowNull()][object]$InputObject, [Parameter(Mandatory)][string]$Name)
    if ($null -eq $InputObject) { return $null }
    if ($InputObject -is [Collections.IDictionary]) {
        if ($InputObject.Contains($Name)) { return $InputObject[$Name] }
        return $null
    }
    $property = $InputObject.PSObject.Properties[$Name]
    if ($property) { return $property.Value }
    return $null
}

function Get-RequiredEnvironmentValue {
    param([Parameter(Mandatory)][string]$Name)
    $value = [Environment]::GetEnvironmentVariable($Name)
    if ([string]::IsNullOrWhiteSpace($value)) { throw "Required environment variable $Name is not set." }
    return $value
}

function Get-DeliveryKey {
    param([Parameter(Mandatory)][object[]]$Rows)
    $identifiers = @($Rows | ForEach-Object {
        $eventId = Get-SafeValue $_ 'eventId'
        if ($eventId) { [string]$eventId } else { "$(Get-SafeValue $_ 'alertId')|$(Get-SafeValue $_ 'observedUtc')" }
    } | Sort-Object -Unique)
    $bytes = [Text.Encoding]::UTF8.GetBytes(($identifiers -join '|'))
    return [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData($bytes)).ToLowerInvariant()
}

function Assert-HttpsEndpoint {
    param([Parameter(Mandatory)][uri]$Uri, [Parameter(Mandatory)][string]$Name)
    if ($Uri.Scheme -ne 'https') { throw "$Name must use HTTPS." }
}

function Send-Summary {
    param([Parameter(Mandatory)][Collections.IDictionary]$Summary)
    if ($DryRun) {
        Write-Host "[DRY RUN] $($Summary | ConvertTo-Json -Compress)"
        return
    }
    switch ($IntegrationType) {
        'slack' {
            $endpoint = [uri](Get-RequiredEnvironmentValue 'DLP_SLACK_WEBHOOK_URL')
            Assert-HttpsEndpoint $endpoint 'DLP_SLACK_WEBHOOK_URL'
            $text = "DLP incident $($Summary.incidentId) | $($Summary.severity) | $($Summary.policy) | $($Summary.detectionCount) detection(s) | $($Summary.incidentUrl)"
            Invoke-RestMethod -Method Post -Uri $endpoint -ContentType 'application/json' -Body (@{ text = $text } | ConvertTo-Json -Compress) | Out-Null
        }
        'servicenow' {
            $instance = [uri](Get-RequiredEnvironmentValue 'DLP_SERVICENOW_INSTANCE')
            Assert-HttpsEndpoint $instance 'DLP_SERVICENOW_INSTANCE'
            $token = Get-RequiredEnvironmentValue 'DLP_SERVICENOW_TOKEN'
            $table = [Environment]::GetEnvironmentVariable('DLP_SERVICENOW_TABLE')
            if ([string]::IsNullOrWhiteSpace($table)) { $table = 'incident' }
            if ($table -notmatch '^[a-zA-Z0-9_]+$') { throw 'DLP_SERVICENOW_TABLE contains invalid characters.' }
            $endpoint = [uri]::new($instance, "/api/now/table/$table")
            $body = [ordered]@{
                short_description = "DLP incident $($Summary.incidentId): $($Summary.policy)"
                description = "Severity: $($Summary.severity)\nDetections: $($Summary.detectionCount)\nObserved UTC: $($Summary.observedUtc)\nMicrosoft Defender: $($Summary.incidentUrl)"
                correlation_id = "dlp-$($Summary.deliveryKey)"
                category = 'security'
            }
            Invoke-RestMethod -Method Post -Uri $endpoint -Headers @{ Authorization = "Bearer $token"; Accept = 'application/json' } -ContentType 'application/json' -Body ($body | ConvertTo-Json) | Out-Null
        }
        'webhook' {
            $endpoint = [uri](Get-RequiredEnvironmentValue 'DLP_WEBHOOK_URL')
            Assert-HttpsEndpoint $endpoint 'DLP_WEBHOOK_URL'
            $headers = @{ Accept = 'application/json' }
            $token = [Environment]::GetEnvironmentVariable('DLP_WEBHOOK_TOKEN')
            if (-not [string]::IsNullOrWhiteSpace($token)) { $headers['Authorization'] = "Bearer $token" }
            Invoke-RestMethod -Method Post -Uri $endpoint -Headers $headers -ContentType 'application/json' -Body ($Summary | ConvertTo-Json -Depth 8) | Out-Null
        }
        default { throw "Unsupported integration type: $IntegrationType" }
    }
}

if ($StudioUrl.Scheme -ne 'http' -or $StudioUrl.Host -notin @('127.0.0.1', 'localhost', '::1')) {
    throw 'StudioUrl must be an HTTP loopback address. Keep Response Studio local and authenticate separately to the destination.'
}

$state = if (Test-Path -LiteralPath $StatePath) {
    try { Get-Content -LiteralPath $StatePath -Raw | ConvertFrom-Json -Depth 10 -ErrorAction Stop }
    catch { throw "The sync state file is invalid: $($_.Exception.Message)" }
} else { [pscustomobject]@{} }
$previousWatermark = Get-SafeValue $state 'lastSuccessfulSyncUtc'
$fromUtc = if ($previousWatermark) { ([datetime]$previousWatermark).ToUniversalTime().AddMinutes(-15) } else { (Get-Date).ToUniversalTime().AddHours(-$InitialLookbackHours) }
$sentKeys = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
foreach ($key in @(Get-SafeValue $state 'sentKeys')) { if ($key) { [void]$sentKeys.Add([string]$key) } }

$queryBody = @{ dateFrom = $fromUtc.ToString('o') } | ConvertTo-Json
$response = Invoke-RestMethod -Method Post -Uri ([uri]::new($StudioUrl, '/api/dlp/query')) -ContentType 'application/json' -Body $queryBody
if ((Get-SafeValue $response 'ok') -ne $true) { throw "Response Studio query failed: $(Get-SafeValue $response 'error')" }
if ((Get-SafeValue $response 'truncated') -eq $true) { throw 'Response Studio scan was truncated. Increase its scan cap before advancing integration state.' }
$rows = @(Get-SafeValue $response 'rows')
$matchedCount = [int](Get-SafeValue $response 'matchedCount')
if ($matchedCount -gt $rows.Count) { throw "Response Studio returned $($rows.Count) of $matchedCount matching rows. Narrow the interval or increase maxResultRows before syncing." }

$delivered = 0
$skipped = 0
$groups = @($rows | Group-Object {
    $incident = Get-SafeValue $_ 'incidentId'
    if ($incident) { "incident:$incident" } else { "alert:$(Get-SafeValue $_ 'alertId')" }
})
foreach ($group in $groups) {
    $groupRows = @($group.Group)
    $deliveryKey = Get-DeliveryKey $groupRows
    if ($sentKeys.Contains($deliveryKey)) { $skipped++; continue }
    $first = $groupRows[0]
    $observed = @($groupRows | ForEach-Object { Get-SafeValue $_ 'observedUtc' } | Where-Object { $_ } | Sort-Object -Descending | Select-Object -First 1)
    $summary = [ordered]@{
        schemaVersion = 1
        source = 'DLP Response Studio'
        integration = $IntegrationName
        deliveryKey = $deliveryKey
        incidentId = [string](Get-SafeValue $first 'incidentId')
        alertId = [string](Get-SafeValue $first 'alertId')
        severity = [string](Get-SafeValue $first 'severity')
        status = [string](Get-SafeValue $first 'status')
        policy = ([string](Get-SafeValue $first 'policy')).Substring(0, [Math]::Min(200, ([string](Get-SafeValue $first 'policy')).Length))
        detectionCount = $groupRows.Count
        observedUtc = if ($observed.Count) { [string]$observed[0] } else { $null }
        incidentUrl = [string](Get-SafeValue $first 'incidentUrl')
    }
    Send-Summary $summary
    [void]$sentKeys.Add($deliveryKey)
    $delivered++
}

if (-not $DryRun) {
    $stateDocument = [ordered]@{
        schemaVersion = 1
        integrationType = $IntegrationType
        lastSuccessfulSyncUtc = (Get-Date).ToUniversalTime().ToString('o')
        sentKeys = @($sentKeys | Select-Object -Last 5000)
    }
    $parent = Split-Path -Parent $StatePath
    if ($parent) { New-Item -ItemType Directory -Path $parent -Force | Out-Null }
    $temp = "$StatePath.$PID.tmp"
    $stateDocument | ConvertTo-Json -Depth 10 | Set-Content -LiteralPath $temp -Encoding utf8
    Move-Item -LiteralPath $temp -Destination $StatePath -Force
}

[pscustomobject]@{ integration = $IntegrationName; provider = $IntegrationType; fromUtc = $fromUtc.ToString('o'); matchedRows = $rows.Count; delivered = $delivered; skippedAlreadyDelivered = $skipped; dryRun = [bool]$DryRun } | Format-List
`;
}

function generateIntegration(input) {
  const spec = normalizeSpec(input);
  const code = powerShell(spec);
  if (/DetectedValues|detectedValues|api[-_ ]?key\s*=|password\s*=/i.test(code)) throw new Error('Generated integration failed the sensitive-data safety check.');
  const provider = PROVIDERS[spec.provider];
  return {
    ok: true,
    spec,
    fileName: spec.fileName,
    language: 'powershell',
    code,
    sha256: crypto.createHash('sha256').update(code, 'utf8').digest('hex'),
    provider: { ...provider, optionalEnvironment: provider.optionalEnvironment || [] },
    safety: [
      'The script queries only the redacted Response Studio projection over loopback.',
      'Detected values, document names, users, senders, and recipients are not included in destination payloads.',
      'Credentials are read from environment variables and are not written to the script or state file.',
      'Response Studio exports this code but never stores it as a flow action or executes it.',
      'Run with -DryRun and review the destination payload before scheduling.',
    ],
  };
}

module.exports = { generateIntegration, normalizeSpec, PROVIDERS };
